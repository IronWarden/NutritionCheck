// Generates supabase/seed.sql from data/claims.json.
// Run after editing the claim library: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const library = JSON.parse(readFileSync(new URL("data/claims.json", root), "utf8"));

const sql = (value) => {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
};
const json = (value) => `${sql(JSON.stringify(value))}::jsonb`;
const textArray = (values) => `array[${values.map(sql).join(", ")}]::text[]`;

const claimIds = new Set(library.claims.map((c) => c.id));
for (const diet of library.diets) {
  for (const id of diet.claim_ids) {
    if (!claimIds.has(id)) throw new Error(`Diet ${diet.id} references unknown claim ${id}`);
  }
}

const claimRows = library.claims.map((c) => {
  const sources = c.sources.map(({ query, ...s }) => ({
    ...s,
    url: `https://pubmed.ncbi.nlm.nih.gov/?term=${encodeURIComponent(query)}`,
  }));
  const values = [
    sql(c.id), sql(c.category), sql(c.title), sql(c.exposure), sql(c.outcome), sql(c.population),
    sql(c.direction), sql(c.effect), sql(c.confidence), sql(c.confidence_reasons), sql(c.summary),
    json(c.triggers), json(sources), sql(c.review_status ?? "draft"),
  ];
  return `  (${values.join(", ")})`;
});

const dietRows = library.diets.map((d) => `  (${sql(d.id)}, ${sql(d.name)}, ${textArray(d.claim_ids)})`);

const out = `-- Generated by scripts/build-seed.mjs from data/claims.json. Do not edit by hand.
insert into public.claims
  (id, category, title, exposure, outcome, population, direction, effect, confidence,
   confidence_reasons, summary, triggers, sources, review_status)
values
${claimRows.join(",\n")}
on conflict (id) do update set
  category = excluded.category, title = excluded.title, exposure = excluded.exposure,
  outcome = excluded.outcome, population = excluded.population, direction = excluded.direction,
  effect = excluded.effect, confidence = excluded.confidence,
  confidence_reasons = excluded.confidence_reasons, summary = excluded.summary,
  triggers = excluded.triggers, sources = excluded.sources,
  review_status = excluded.review_status, updated_at = now();

insert into public.diets (id, name, claim_ids)
values
${dietRows.join(",\n")}
on conflict (id) do update set name = excluded.name, claim_ids = excluded.claim_ids;
`;

writeFileSync(new URL("supabase/seed.sql", root), out);
console.log(`Wrote ${library.claims.length} claims and ${library.diets.length} diets to supabase/seed.sql`);
